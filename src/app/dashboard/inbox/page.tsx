"use client";

import React, { useMemo, useState } from "react";
import Link from "next/link";
import { BellRing, CheckCheck, Inbox as InboxIcon } from "lucide-react";
import { useCivic } from "@/lib/store";
import { PageHeader, EmptyState } from "@/components/ui";
import { timeAgo, formatDateTime } from "@/lib/utils";
import type { NotificationType } from "@/types";

const TYPE_STYLE: Record<NotificationType, { bg: string; fg: string; label: string }> = {
  request_created: { bg: "#E7ECEF", fg: "#274C77", label: "New file" },
  status_change: { bg: "#D8E8F5", fg: "#274C77", label: "Status update" },
  action_required: { bg: "#F7EBCF", fg: "#7A5A1F", label: "Action needed" },
  completed: { bg: "#D9EBE3", fg: "#2E6B57", label: "Completed" },
  overdue: { bg: "#F3DEDE", fg: "#8E4444", label: "Overdue (sample)" },
  info: { bg: "#EDEFF2", fg: "#4A5C6E", label: "Info" },
};

export default function InboxPage() {
  const { myNotifications, markRead, markAllRead, unreadCount } = useCivic();
  const [filter, setFilter] = useState<"all" | "unread" | "updates">("all");

  const filtered = useMemo(() => {
    if (filter === "unread") return myNotifications.filter((n) => !n.isRead);
    if (filter === "updates") return myNotifications.filter((n) => ["status_change", "action_required", "overdue", "completed"].includes(n.type));
    return myNotifications;
  }, [myNotifications, filter]);

  return (
    <div className="space-y-5">
      <PageHeader
        eyebrow="Notification center"
        title="Inbox"
        copy="Prototype messages generated by status changes, new files, and sample overdue flags. No emails or push messages are sent."
        actions={
          <button onClick={markAllRead} disabled={unreadCount === 0} className="inline-flex items-center gap-2 rounded-full border border-[#DCE4E9] bg-white px-4 py-2 text-[13px] font-semibold text-[#274C77] hover:border-[#6096BA] disabled:opacity-50">
            <CheckCheck size={15} /> Mark all as read
          </button>
        }
      />

      <div className="flex flex-wrap items-center gap-2">
        {([["all", "All"], ["unread", `Unread (${unreadCount})`], ["updates", "Request updates"]] as const).map(([v, label]) => (
          <button key={v} onClick={() => setFilter(v)} className={`rounded-full px-4 py-2 text-[13px] font-semibold transition ${filter === v ? "bg-[#274C77] text-white" : "border border-[#DCE4E9] bg-white text-[#4A5C6E] hover:border-[#6096BA]"}`}>
            {label}
          </button>
        ))}
      </div>

      {filtered.length === 0 ? (
        <EmptyState
          title={filter === "unread" ? "All caught up" : "No messages"}
          copy={filter === "unread" ? "Every prototype message has been read. New status changes will appear here." : "Messages about your files will land here as events occur."}
          action={<Link href="/dashboard/requests" className="rounded-full bg-[#274C77] px-5 py-2.5 text-[13px] font-semibold text-white">View requests</Link>}
        />
      ) : (
        <ul className="space-y-2.5">
          {filtered.map((n) => {
            const s = TYPE_STYLE[n.type];
            return (
              <li key={n.id} className={`group relative overflow-hidden rounded-3xl border bg-white p-5 transition ${n.isRead ? "border-[#DCE4E9]" : "border-[#6096BA66] shadow-[0_12px_30px_rgba(39,76,119,0.10)]"}`}>
                {!n.isRead && <span className="absolute top-0 left-0 h-full w-1 bg-gradient-to-b from-[#274C77] to-[#6096BA]" aria-hidden />}
                <div className="flex flex-wrap items-center gap-2">
                  <span className="rounded-full px-2.5 py-1 text-[11px] font-bold" style={{ background: s.bg, color: s.fg }}>{s.label}</span>
                  {!n.isRead && <span className="h-2 w-2 rounded-full bg-[#6096BA] pulse-dot" aria-label="Unread" />}
                  <span className="ml-auto text-[11px] text-[#9AA9B7]" title={formatDateTime(n.createdAt)}>{timeAgo(n.createdAt)}</span>
                </div>
                <h3 className="mt-2 text-[15px] font-semibold">{n.title}</h3>
                <p className="mt-1 text-[13px] leading-relaxed text-[#4A5C6E]">{n.message}</p>
                <div className="mt-3 flex flex-wrap gap-2">
                  {n.requestId && (
                    <Link href={`/dashboard/requests/${n.requestId}`} className="cut-corner-sm inline-flex items-center gap-1.5 bg-[#274C77] px-4 py-2 text-xs font-semibold text-white hover:bg-[#1e3c5e]">
                      Open {n.requestId}
                    </Link>
                  )}
                  {!n.isRead && (
                    <button onClick={() => markRead(n.id)} className="inline-flex items-center gap-1.5 rounded-full border border-[#DCE4E9] px-4 py-2 text-xs font-semibold text-[#4A5C6E] hover:border-[#6096BA] hover:text-[#274C77]">
                      <BellRing size={13} /> Mark as read
                    </button>
                  )}
                </div>
              </li>
            );
          })}
        </ul>
      )}
      <p className="flex items-center gap-2 text-xs text-[#9AA9B7]"><InboxIcon size={13} /> {myNotifications.length} total messages · {unreadCount} unread · stored locally, derived from your events.</p>
    </div>
  );
}
